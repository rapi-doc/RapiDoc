import { GLOBAL_OPTIONS } from "./args.js";

/*
 * Shell completion scripts for zsh, bash and fish, generated from the command declarations (the same
 * `options` and `positionals` that make the help), so they can't drift from the commands. Each script
 * is self-contained: completing never runs the CLI.
 *
 * What is completed: command names (with their summaries where the shell shows them), each command's
 * options (long and short, `--no-` forms of negatable ones), the values of options with `choices`,
 * files for options whose value is a file or path, and positionals: `positionals.choices` for the first
 * one (mcp's export|serve), files otherwise.
 */

const FILE_VALUES = new Set(["file", "path", "dir", "spec", "dist", "spec|dir"]);

/** The options of a command, global ones included, as flat records. */
function optionsOf(command) {
  return Object.entries({ ...command.options, ...GLOBAL_OPTIONS }).map(([name, def]) => ({
    name,
    short: def.short,
    takesValue: def.type === "string",
    choices: def.choices,
    files: def.type === "string" && FILE_VALUES.has(def.value),
    negatable: Boolean(def.negatable),
    multiple: Boolean(def.multiple),
    description: (def.description ?? "").replace(/\s*\n\s*/g, " "),
  }));
}

const flagsOf = (option) => [
  `--${option.name}`,
  ...(option.negatable ? [`--no-${option.name}`] : []),
  ...(option.short ? [`-${option.short}`] : []),
];

const sq = (text) => `'${String(text).replace(/'/g, "'\\''")}'`;

// ---------------------------------------------------------------------------------------------- zsh

const zshDescription = (text) => String(text).replace(/[[\]:]/g, "\\$&");

function zshOption(option) {
  const desc = `[${zshDescription(option.description)}]`;
  const star = option.multiple ? "*" : "";
  let value = "";
  if (option.takesValue) {
    const action = option.choices ? `(${option.choices.join(" ")})` : option.files ? "_files" : "";
    value = `:${option.name}:${action}`;
  }
  if (option.short && !option.negatable)
    return `${sq(`(-${option.short} --${option.name})`)}{-${option.short},--${option.name}}${sq(`${desc}${value}`)}`;
  const forms = option.negatable
    ? [`--${option.name}`, `--no-${option.name}`]
    : [`--${option.name}`];
  return forms.map((form) => sq(`${star}${form}${desc}${value}`)).join(" ");
}

function zshPositionals(command) {
  const spec = command.positionals;
  if (!spec) return [];
  const out = [];
  if (spec.choices) out.push(sq(`1:${spec.name}:(${spec.choices.join(" ")})`));
  out.push(sq(`*:${spec.choices ? "file" : spec.name}:_files`));
  return out;
}

export function zsh(commands) {
  const names = commands
    .map((command) => sq(`${command.name}:${zshDescription(command.summary)}`))
    .join("\n    ");
  const cases = commands
    .map(
      (command) =>
        `    ${command.name})\n      _arguments -s ${[...optionsOf(command).map(zshOption), ...zshPositionals(command)].join(" \\\n        ")}\n      ;;`,
    )
    .join("\n");
  return `#compdef rapidoc
# zsh completion for rapidoc, generated by \`rapidoc completion zsh\`.

_rapidoc() {
  local -a commands
  commands=(
    ${names}
    'help:Show help for a command'
  )
  local context state state_descr line
  typeset -A opt_args
  _arguments -C \\
    '(- *)'{-h,--help}'[Show help]' \\
    '(- *)'{-v,--version}'[Show the version]' \\
    '1: :->command' \\
    '*:: :->args' && return
  case $state in
    command) _describe -t commands 'rapidoc command' commands ;;
    args)
      case $words[1] in
${cases}
    help) _describe -t commands 'rapidoc command' commands ;;
      esac
      ;;
  esac
}

if [ "$funcstack[1]" = "_rapidoc" ]; then
  _rapidoc "$@"
else
  compdef _rapidoc rapidoc
fi
`;
}

// --------------------------------------------------------------------------------------------- bash

export function bash(commands) {
  const names = [...commands.map((command) => command.name), "help"].join(" ");
  const cases = commands
    .map((command) => {
      const options = optionsOf(command);
      const flags = options.flatMap(flagsOf).join(" ");
      const valued = options
        .filter((option) => option.takesValue)
        .map((option) => {
          const forms = flagsOf(option).join("|");
          const action = option.choices
            ? `COMPREPLY=($(compgen -W "${option.choices.join(" ")}" -- "$cur"))`
            : option.files
              ? 'COMPREPLY=($(compgen -f -- "$cur"))'
              : "COMPREPLY=()";
          return `        ${forms}) ${action}; return ;;`;
        })
        .join("\n");
      const first = command.positionals?.choices
        ? `      if [[ $npos -eq 0 && "$cur" != -* ]]; then COMPREPLY=($(compgen -W "${command.positionals.choices.join(" ")}" -- "$cur")); return; fi\n`
        : "";
      const positional = command.positionals
        ? 'COMPREPLY=($(compgen -f -- "$cur"))'
        : "COMPREPLY=()";
      return `    ${command.name})
      case "$prev" in
${valued}
      esac
${first}      if [[ "$cur" == -* ]]; then COMPREPLY=($(compgen -W "${flags}" -- "$cur")); return; fi
      ${positional} ;;`;
    })
    .join("\n");
  return `# bash completion for rapidoc, generated by \`rapidoc completion bash\`.

_rapidoc() {
  local cur prev cmd i npos
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  cmd=""
  npos=0
  for ((i = 1; i < COMP_CWORD; i++)); do
    case "\${COMP_WORDS[i]}" in
      -*) ;;
      *) if [[ -z "$cmd" ]]; then cmd="\${COMP_WORDS[i]}"; else npos=$((npos + 1)); fi ;;
    esac
  done
  if [[ -z "$cmd" ]]; then
    COMPREPLY=($(compgen -W "${names} --help --version" -- "$cur"))
    return
  fi
  case "$cmd" in
${cases}
    help) COMPREPLY=($(compgen -W "${names}" -- "$cur")) ;;
  esac
}

complete -F _rapidoc rapidoc
`;
}

// --------------------------------------------------------------------------------------------- fish

export function fish(commands) {
  const lines = [
    "# fish completion for rapidoc, generated by `rapidoc completion fish`.",
    "",
    "complete -c rapidoc -f",
  ];
  lines.push(
    "complete -c rapidoc -n __fish_use_subcommand -s h -l help -d 'Show help'",
    "complete -c rapidoc -n __fish_use_subcommand -s v -l version -d 'Show the version'",
  );
  for (const command of commands)
    lines.push(
      `complete -c rapidoc -n __fish_use_subcommand -a ${command.name} -d ${sq(command.summary)}`,
    );
  lines.push("complete -c rapidoc -n __fish_use_subcommand -a help -d 'Show help for a command'");
  for (const command of commands) {
    const when = `-n '__fish_seen_subcommand_from ${command.name}'`;
    lines.push("", `# rapidoc ${command.name}`);
    for (const option of optionsOf(command)) {
      const short = option.short && !option.negatable ? ` -s ${option.short}` : "";
      const value = option.takesValue
        ? option.choices
          ? ` -r -a '${option.choices.join(" ")}'`
          : option.files
            ? " -r -F"
            : " -r"
        : "";
      lines.push(
        `complete -c rapidoc ${when}${short} -l ${option.name}${value} -d ${sq(option.description)}`,
      );
      if (option.negatable)
        lines.push(`complete -c rapidoc ${when} -l no-${option.name} -d ${sq(option.description)}`);
    }
    if (command.positionals?.choices)
      lines.push(
        `complete -c rapidoc ${when} -n 'not __fish_seen_subcommand_from ${command.positionals.choices.join(" ")}' -a '${command.positionals.choices.join(" ")}'`,
      );
    if (command.positionals) lines.push(`complete -c rapidoc ${when} -F`);
  }
  lines.push(
    "",
    `complete -c rapidoc -n '__fish_seen_subcommand_from help' -a '${commands.map((c) => c.name).join(" ")}'`,
    "",
  );
  return lines.join("\n");
}
